object StringsProvider {
    fun getLocale(lang: String): Locale = when (lang) {
        "it" -> Locale.ITALIAN
        "en" -> Locale.ENGLISH
        else -> Locale.FRANCE
    }

    fun t(lang: String, key: String, vararg args: Any): String {
        val template = when (lang) {
            "it" -> itMap[key] ?: frMap[key] ?: key
            "en" -> enMap[key] ?: frMap[key] ?: key
            else -> frMap[key] ?: key
        }
        return if (args.isEmpty()) template else String.format(getLocale(lang), template, *args)
    }

